/**
 * تطبيع النص العربي: توحيد الهمزات، إزالة التشكيل والرموز.
 * مُعرّفة هنا لأن products.js تُحمّل قبل bot.js.
 */
function normalizeArabic(text) {
  return String(text)
    .trim()
    .toLowerCase()
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[ًٌٍَُِّْـ]/g, "")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * كلمات وقفية شائعة لا تدل على منتج — نتجاهلها في البحث.
 * بدونها، "عندكم زعفران؟" تنجح بالصدفة و"ابغى شي للنوم" تفشل.
 */
const STOP_WORDS = new Set([
  "عندكم", "عندك", "ابغي", "ابغى", "اريد", "أريد", "بدي", "ودي",
  "هل", "في", "من", "على", "عن", "مع", "شي", "شيء", "حاجه", "حاجة",
  "لو", "سمحت", "ممكن", "كم", "سعر", "اسعار", "بكم", "كيف", "وين", "فين",
  "ايش", "ايش", "شنو", "وش", "اللي", "الذي", "هذا", "هذه", "انت", "انتم",
  "عند", "لديكم", "لديكم", "بيع", "تبيعون", "متوفر", "متوفره", "موجود",
]);

/**
 * تجريد السوابق العربية الشائعة (ال، لل، بال، وال، فال، كال…)
 * مثال: "للنوم" -> "نوم"، "بالاعصاب" -> "اعصاب"
 */
function stripArabicPrefix(word) {
  let w = word;
  // سوابق مركبة أولاً
  const compound = ["وبال", "وال", "فال", "بال", "كال", "لل", "ال"];
  for (const p of compound) {
    if (w.startsWith(p) && w.length - p.length >= 3) {
      w = w.slice(p.length);
      break;
    }
  }
  return w;
}

/**
 * بحث ذكي في المنتجات بالكلمات المفتاحية والاسم.
 * - يطبّع النص العربي أولاً
 * - يتجاهل كلمات الوقف
 * - يجرّد السوابق (لل / بال / ال) لمطابقة الجذور
 * - يطابق على مستوى الكلمة (وليس السلسلة الكاملة)
 *
 * @param {string} query - نص بحث العميل
 * @returns {Array} - المنتجات المطابقة مرتبة حسب قوة التطابق
 */
function searchProducts(query) {
  if (!query) return [];

  const norm = normalizeArabic(query);
  if (!norm) return [];

  const rawWords = norm
    .split(/\s+/)
    .filter((w) => w.length >= 3 && !STOP_WORDS.has(w));

  // نضيف الجذور المجرّدة لكل كلمة
  const words = [];
  rawWords.forEach((w) => {
    words.push(w);
    const stem = stripArabicPrefix(w);
    if (stem !== w && stem.length >= 3) words.push(stem);
  });

  if (words.length === 0) return [];

  const scored = PRODUCTS.map((p) => {
    const haystack = normalizeArabic(
      [p.name, p.category, ...p.tags].join(" ")
    );
    // جرّد سوابق كلمات المخزون أيضاً للمقارنة بالجذور
    const hayWords = haystack.split(/\s+/);
    const hayExpanded = new Set(hayWords);
    hayWords.forEach((hw) => {
      const s = stripArabicPrefix(hw);
      if (s) hayExpanded.add(s);
    });

    let score = 0;
    words.forEach((w) => {
      // تطابق كامل للكلمة (حدود الكلمة) = قوة أكبر
      if (hayExpanded.has(w)) score += 3;
      // تطابق جزئي (الكلمة داخل سلسلة أطول) = قوة أقل
      else if (haystack.includes(w)) score += 1;
    });

    return { product: p, score };
  });

  const matched = scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.product);

  return matched;
}

